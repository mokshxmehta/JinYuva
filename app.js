function contactHref() {
  const p = (JINYUVA_CONFIG.CONTACT_PHONE || '').replace(/\D/g, '');

  return p
    ? `tel:+91${p}`
    : '#';
}

function calculateAge(dob) {
  const b = new Date(`${dob}T00:00:00`);
  const now = new Date();

  let age = now.getFullYear() - b.getFullYear();

  const m = now.getMonth() - b.getMonth();

  if (m < 0 || (m === 0 && now.getDate() < b.getDate())) {
    age--;
  }

  return age;
}

function getSanghValue() {
  const selected = $('sangh').value;

  if (selected === 'Other') {
    return $('otherSangh').value.trim();
  }

  return selected.trim();
}

function validSangh() {
  const selected = $('sangh').value;

  if (!selected) {
    return false;
  }

  if (selected === 'Other') {
    return $('otherSangh').value.trim().length > 0;
  }

  return true;
}

function clearErrors() {
  document.querySelectorAll('.error').forEach(e => {
    e.textContent = '';
  });
}

function validate() {
  clearErrors();

  const t = translations[lang];
  let ok = true;

  const name = $('name').value.trim();
  const phone = $('phone').value.replace(/\D/g, '');
  const dob = $('dob').value;
  const sangh = getSanghValue();
  const confirm = $('confirm').checked;

  if (!name) {
    setText('nameError', t.required);
    ok = false;
  }

  if (!/^\d{10}$/.test(phone)) {
    setText('phoneError', t.phoneInvalid);
    ok = false;
  }

  if (!dob) {
    setText('dobError', t.required);
    ok = false;
  } else {
    const selectedDate = new Date(`${dob}T00:00:00`);
    const today = new Date();

    today.setHours(0, 0, 0, 0);

    if (isNaN(selectedDate.getTime())) {
      setText('dobError', t.dobInvalid);
      ok = false;
    } else if (selectedDate > today) {
      setText('dobError', 'Date of birth cannot be in the future.');
      ok = false;
    } else {
      const age = calculateAge(dob);

      if (age < 10) {
        setText('dobError', t.ageRange);
        ok = false;
      } else if (age > 120) {
        setText('dobError', t.dobInvalid);
        ok = false;
      }
    }
  }

  if (!validSangh()) {
    setText('sanghError', t.sanghInvalid);
    ok = false;
  }

  if (!confirm) {
    setText('confirmError', t.confirmInvalid);
    ok = false;
  }

  return ok;
}

function parseLoginDob(value) {
  const v = value.trim();

  if (v === '01/01/01') {
    return 'ADMIN_SPECIAL_DATE';
  }

  const match = v.match(/^(\d{1,2})\/(\d{1,2})\/(\d{4})$/);

  if (!match) {
    return null;
  }

  const day = Number(match[1]);
  const month = Number(match[2]);
  const year = Number(match[3]);

  if (year < 1 || month < 1 || month > 12 || day < 1 || day > 31) {
    return null;
  }

  const date = new Date(year, month - 1, day);

  if (
    date.getFullYear() !== year ||
    date.getMonth() !== month - 1 ||
    date.getDate() !== day
  ) {
    return null;
  }

  return `${String(day).padStart(2, '0')}/${String(month).padStart(2, '0')}/${year}`;
}

